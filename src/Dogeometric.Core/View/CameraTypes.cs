namespace Dogeometric.Core.View;

/// <summary>A film, video or photo camera of Advanced Camera Tools: its gate's width (mm) and proportions.</summary>
public sealed record CameraType(string Category, string Name, double SensorWidthMm, double Aspect)
{
    /// <summary>The horizontal field of view a lens of <paramref name="focalMm"/> gives on this camera.</summary>
    public double HorizontalFov(double focalMm) => 2 * Math.Atan(SensorWidthMm / (2 * focalMm)) * 180 / Math.PI;

    /// <summary>The vertical field of view (what the view's field of view measures) for that lens.</summary>
    public double VerticalFov(double focalMm) => 2 * Math.Atan(SensorWidthMm / Aspect / (2 * focalMm)) * 180 / Math.PI;
}

